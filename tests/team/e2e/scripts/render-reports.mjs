// Turns the raw test output into the tables used in the report.
//
//   node scripts/render-reports.mjs
//
// reads   reports/results.json          (Playwright JSON reporter)
//         reports/access/checks.json    (written by the access-control tests)
// writes  reports/e2e_traceability.csv  one row per test: id, requirements, outcome
//         ../../../docs/team/access_results.md
import fs from 'node:fs';
import path from 'node:path';

const root = import.meta.dirname ? path.join(import.meta.dirname, '..') : '.';
const read = (f) => JSON.parse(fs.readFileSync(path.join(root, f), 'utf-8'));

// ---- traceability -------------------------------------------------------
const results = read('reports/results.json');
const rows = [];
function walk(suite) {
  for (const spec of suite.specs ?? []) {
    const reqs = (spec.tags ?? []).map((t) => t.replace(/^@/, '')).sort().join(' ');
    const outcome = spec.tests.map((t) => t.status).join('/'); // expected, unexpected, flaky, skipped
    rows.push([spec.title.replace(/,/g, ';'), reqs, spec.ok ? 'pass' : 'FAIL', outcome]);
  }
  for (const child of suite.suites ?? []) walk(child);
}
for (const suite of results.suites) walk(suite);
const csv = ['test,requirements,result,status'].concat(rows.map((r) => r.join(','))).join('\n') + '\n';
fs.writeFileSync(path.join(root, 'reports/e2e_traceability.csv'), csv);
console.log(`traceability: ${rows.length} tests, ${rows.filter((r) => r[2] === 'pass').length} passing`);

// ---- access checks ------------------------------------------------------
const checksFile = path.join(root, 'reports/access/checks.json');
if (fs.existsSync(checksFile)) {
  const checks = JSON.parse(fs.readFileSync(checksFile, 'utf-8'));
  const lines = [
    '# Access check results',
    '',
    'Generated by `tests/team/e2e/scripts/render-reports.mjs` from `reports/access/checks.json`,',
    'which the tests in `tests/team/e2e/specs/security/access-control.spec.ts` write when they run.',
    '',
    '| Id | Role | Action | Expected | Observed | Result | Evidence |',
    '| --- | --- | --- | --- | --- | --- | --- |',
    ...checks.map(
      (c) => `| ${c.id} | ${c.role} | ${c.action} | ${c.expected} | ${c.observed} | ${c.pass ? 'pass' : 'FAIL'} | \`${c.evidence}\` |`,
    ),
    '',
  ];
  const out = path.join(root, '..', '..', '..', 'docs', 'team', 'access_results.md');
  fs.writeFileSync(out, lines.join('\n'));
  console.log(`access results: ${checks.length} checks`);
}
