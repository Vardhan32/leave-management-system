// Before-and-after comparison of the axe and Lighthouse runs.
//
//   node scripts/compare-a11y.mjs
//
// reads  reports/axe/{before,after}/*.json  and  reports/lighthouse/{before,after}/summary.json
// writes ../../../docs/team/accessibility_before_after.md
import fs from 'node:fs';
import path from 'node:path';

const root = path.join(import.meta.dirname, '..');
const load = (p) => JSON.parse(fs.readFileSync(path.join(root, p), 'utf-8'));

function axeCounts(phase) {
  const dir = path.join(root, 'reports', 'axe', phase);
  const out = {};
  for (const file of fs.readdirSync(dir).filter((f) => f.endsWith('.json'))) {
    const j = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf-8'));
    out[j.screen] = {
      rules: j.violations.length,
      elements: j.violations.reduce((n, v) => n + v.nodes.length, 0),
      ids: j.violations.map((v) => `${v.id}(${v.nodes.length})`).join(', ') || 'none',
    };
  }
  return out;
}

const axeBefore = axeCounts('before');
const axeAfter = axeCounts('after');
const lhBefore = load('reports/lighthouse/before/summary.json');
const lhAfter = load('reports/lighthouse/after/summary.json');

const lines = [
  '# Accessibility: before and after the fix',
  '',
  'Generated by `tests/team/e2e/scripts/compare-a11y.mjs`. Same machine, same seeded data, production build of the app.',
  '',
  `axe-core ${Object.values(axeBefore).length ? load('reports/axe/before/login.json').axeVersion : ''} (tags wcag2a, wcag2aa, wcag21a, wcag21aa, wcag22aa, best-practice) and Lighthouse ${lhBefore.lighthouseVersion} (accessibility, best practices, SEO, desktop preset).`,
  '',
  '## axe-core violations',
  '',
  '| Screen | Before: rules / elements | After: rules / elements | Rules before | Rules after |',
  '| --- | --- | --- | --- | --- |',
  ...Object.keys(axeBefore).map((s) => {
    const b = axeBefore[s];
    const a = axeAfter[s] ?? { rules: '-', elements: '-', ids: '-' };
    return `| ${s} | ${b.rules} / ${b.elements} | ${a.rules} / ${a.elements} | ${b.ids} | ${a.ids} |`;
  }),
  '',
  '## Lighthouse scores',
  '',
  '| Screen | Accessibility before | after | Best practices before | after | SEO before | after |',
  '| --- | --- | --- | --- | --- | --- | --- |',
  ...Object.keys(lhBefore.screens).map((s) => {
    const b = lhBefore.screens[s].scores;
    const a = lhAfter.screens[s]?.scores ?? {};
    return `| ${s} | ${b.accessibility} | ${a.accessibility} | ${b['best-practices']} | ${a['best-practices']} | ${b.seo} | ${a.seo} |`;
  }),
  '',
  '## Lighthouse audits still failing',
  '',
  ...Object.keys(lhAfter.screens).map(
    (s) =>
      `- **${s}** before: ${lhBefore.screens[s].failed.map((f) => f.id).join(', ') || 'none'}; after: ${lhAfter.screens[s].failed.map((f) => f.id).join(', ') || 'none'}`,
  ),
  '',
];
const out = path.join(root, '..', '..', '..', 'docs', 'team', 'accessibility_before_after.md');
fs.writeFileSync(out, lines.join('\n'));
console.log('wrote', out);
